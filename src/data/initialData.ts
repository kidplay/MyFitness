export const generateInitialWeightLogs = (): WeightLog[] => {
  const logs: WeightLog[] = [];
  const baseWeight = 79.5;
  const target = 76.5;
  const days = 30;

  for (let i = days; i >= 0; i--) {
    const progress = (days - i) / days;
    // Add minor realistic daily fluctuations (+/- 0.25kg)
    const noise = Math.sin(i * 1.8) * 0.25;
    const weight = Number((baseWeight - progress * (baseWeight - target) + noise).toFixed(1));
    logs.push({
      id: `w-${i}`,
      date: getTodayDateString(-i),
      weightKg: weight,
      note: i === 0 ? 'Morning weigh-in (fasted)' : undefined,
    });
  }
  return logs;
};

